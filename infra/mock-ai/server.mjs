function classify(text) {
  const lower = text.toLowerCase();
  let best = "GENERAL_INQUIRY";
  let bestScore = 0;
  for (const [key, c] of Object.entries(CATEGORIES)) {
    const score = c.words.filter((w) => lower.includes(w)).length;
    if (score > bestScore) { best = key; bestScore = score; }
  }
  return best;
}

// The pipeline rejects citations of knowledge-base chunks that were not offered in the request, so cite only offered ones.
function citationsFor(chunk, prompt) {
  const offered = new Set([...prompt.matchAll(/kb\.[a-z.-]+[a-z]/g)].map((m) => m[0]));
  return offered.has(chunk) ? [chunk] : [];
}

function answer(parsed) {
  const [system = { content: "" }, user = { content: "" }] = parsed.messages ?? [];
  const prompt = String(user.content);
  if (system.content.includes("triage support tickets")) {
    // Key only on the author-written text (the untrusted blocks), not on the policy excerpts that share the prompt.
    const ticketText = [...prompt.matchAll(/<untrusted-([\w]+)[^>]*>([\s\S]*?)<\/untrusted-\1>/g)].map((m) => m[2]).join("\n");
    const category = classify(ticketText);
    const c = CATEGORIES[category];
    return { category, payload: { category, priority: c.priority, confidence: 0.6, rationale: `${DEMO_RATIONALE} Matched ${category}.`, citations: citationsFor(c.chunk, prompt) } };
  }
  const labelled = /TICKET CLASSIFICATION \(system\): (.+?), priority/.exec(prompt)?.[1];
  const category = Object.keys(CATEGORIES).find((k) => CATEGORIES[k].label === labelled) ?? "GENERAL_INQUIRY";
  const c = CATEGORIES[category];
  return { category, payload: { draft: `Dear {{authorFirstName}},\n\n${DEMO_DRAFT_LABEL}\n\n${c.body}\n\nWarm regards,\nBookLeaf Author Support`, citations: citationsFor(c.chunk, prompt) } };
}

const server = http.createServer((req, res) => {
  let body = "";
  req.on("data", (chunk) => { if (body.length < 1_000_000) body += chunk; });
  req.on("end", () => {
    const send = (status, payload) => { res.writeHead(status, { "content-type": "application/json" }); res.end(JSON.stringify(payload)); };
    if (req.method === "GET" && req.url === "/healthz") return send(200, { status: "ok", demo: true });
    if (req.method === "POST" && req.url?.endsWith("/chat/completions")) {
      try {
        const { category, payload } = answer(JSON.parse(body || "{}"));
        console.log(JSON.stringify({ level: "info", method: req.method, path: req.url, status: 200, category }));
        return send(200, {
          choices: [{ message: { role: "assistant", content: JSON.stringify(payload) } }],
          usage: { prompt_tokens: 0, completion_tokens: 0, total_tokens: 0, cost: 0 }
        });
      } catch {
        return send(400, { error: { message: "bad request" } });
      }
    }
    return send(404, {});
  });
});
// Loopback only: inside the API container (see docker-compose.demo.yml) only the API can reach it, and the AI package accepts
// plain http solely for 127.0.0.1/localhost.
const HOST = process.env.MOCK_AI_HOST ?? "127.0.0.1";
server.listen(PORT, HOST, () => console.log(`mock-ai (DEMONSTRATION ONLY) listening on ${HOST}:${PORT}`));
